#!/usr/bin/env python3
"""Turn the house song's MIDI (audio/raw/Soft Melody.mid) into js/notes.js: the notes the music-mode lights follow.
The clarinet solo = tracks 10 and 11 (the cello-named tracks carrying the 'Clarinet Solo' patch). Right hand (the melody) = the piano melody tracks (1-4); left hand = the piano left-hand tracks (5-8) and the accordion bass (14).
Each note is [start s, pitch, length s, velocity 0..127], sorted by start. The MIDI's tempo map matches the recording (checked against SONG_BEATS in js/audio.js).
Run from the project root:  python3 audio/tools/make_notes.py     (no libraries needed)"""
import struct, json
d = open('audio/raw/Soft Melody.mid', 'rb').read()
div = struct.unpack('>H', d[12:14])[0]
nt = struct.unpack('>H', d[10:12])[0]
def vlq(b, i):
    v = 0
    while True:
        c = b[i]; i += 1; v = (v << 7) | (c & 127)
        if not c & 128: return v, i
p = 14; tempos = []; notes = []
for t in range(nt):
    ln = struct.unpack('>I', d[p + 4:p + 8])[0]; b = d[p + 8:p + 8 + ln]; p += 8 + ln
    i = 0; tick = 0; rs = None; on = {}
    while i < len(b):
        dt, i = vlq(b, i); tick += dt; s = b[i]
        if s == 0xFF:
            ty = b[i + 1]; l, j = vlq(b, i + 2); data = b[j:j + l]; i = j + l
            if ty == 0x51: tempos.append((tick, int.from_bytes(data, 'big')))
            continue
        if s in (0xF0, 0xF7): l, j = vlq(b, i + 1); i = j + l; continue
        if s & 128: rs = s; i += 1
        k = rs & 0xF0
        if k in (0xC0, 0xD0): i += 1; continue
        a, v = b[i], b[i + 1]; i += 2
        if k == 0x90 and v > 0: on[(rs & 15, a)] = (tick, v)
        elif k == 0x80 or k == 0x90:
            if (rs & 15, a) in on: t0, vel = on.pop((rs & 15, a)); notes.append((t, t0, tick, a, vel))
tempos.sort()
def sec(tk):
    s = 0; lt = 0; tp = 500000
    for a, b in tempos:
        if a >= tk: break
        s += (a - lt) * tp / div / 1e6; lt = a; tp = b
    return s + (tk - lt) * tp / div / 1e6
def pack(tracks):
    out = sorted((sec(n[1]), n[3], sec(n[2]) - sec(n[1]), n[4]) for n in notes if n[0] in tracks)
    return '[' + ','.join(f'[{a:.2f},{b},{c:.2f},{e}]' for a, b, c, e in out) + ']'
rh, lh, cl, st = pack({1, 2, 3, 4}), pack({5, 6, 7, 8, 14}), pack({10, 11}), pack({13})
# The harmony: for each bar (3 beats = 1440 ticks) the major or minor triad that best fits the notes sounding in it (every track, longer / louder / lower notes count more),
# as [start s, root pitch class 0-11, 1 if minor]; neighbouring bars with the same chord are merged.
bars = max(n[2] for n in notes) // 1440 + 1; chords = []
for k in range(bars):
    lo, hi = k * 1440, (k + 1) * 1440; h = [0.0] * 12
    for n in notes:
        ov = min(hi, n[2]) - max(lo, n[1])
        if ov > 0: h[n[3] % 12] += ov * (n[4] + 20) * (1.6 if n[3] < 55 else 1.0)
    if sum(h) < 1: continue
    best = max(((sum(h[(r + i) % 12] for i in (0, 3 if m else 4, 7)) - 0.45 * sum(h) * 0 - 0.25 * sum(h[(r + i) % 12] for i in range(12) if i not in (0, 3 if m else 4, 7)), r, m) for r in range(12) for m in (0, 1)))
    if not chords or chords[-1][1:] != [best[1], best[2]]: chords.append([round(sec(lo), 2), best[1], best[2]])
cj = '[' + ','.join(f'[{a},{b},{c}]' for a, b, c in chords) + ']'
open('js/notes.js', 'w').write('// Generated by audio/tools/make_notes.py from the song\'s MIDI: [start s, pitch, length s, velocity]. RH is the melody, LH the left hand and the bass.\n'
                              f'export const SONG_RH = {rh};\nexport const SONG_LH = {lh};\n// The clarinet solo (it plays from 0:36 to 1:26): the meteors follow it.\nexport const SONG_CL = {cl};\n// The string pad (Full Strings for Layers, 1:06 to 1:26): the aurora swells with it.\nexport const SONG_ST = {st};\n// The chord of each stretch: [start s, root pitch class (0 = C), 1 if minor].\nexport const SONG_CHORDS = {cj};\n')
print(rh.count('],['), lh.count('],['))
